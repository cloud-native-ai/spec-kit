"""Contract tests for identity and wiring (Feature 078, User Story 4).

Clause source: ``.specify/specs/078-coaching-skills/contracts/identity-and-wiring.contract.md``
(C-1..C-8). This file is the *guard copy* the contract names: it is the one place allowed
to hold the old literal, because the residual audit must be decidable and must derive its
candidate set instead of restating a fifth hand-written path list.

Two things are deliberately mechanical rather than declared here:

* the mirror faces come from ``scripts/python/sync-mirrors.py`` module
  ``MIRROR_PAIRS`` (source side plus mirror side), and
* the per-tool command-copy faces come from ``specify_cli._ASSISTANT_COMMAND_DIRS``
  filtered to the directories that actually exist — the same table
  ``scripts/python/regen-command-copies.py`` fans out from.

Only A10's residual members that no generator reaches are pinned as literals below, and
each is pinned with the reason it is unreachable.

Sanctioned manifests: both ``src/specify_cli/__init__.py`` and
``scripts/python/sanitize-utils.py`` carry an ``OBSOLETE-ASSET-REGISTRY`` block that names
retired skills **in order to delete them**. That block is stripped before counting, and
the CLI tuple entry is then asserted as the single permitted occurrence.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from functools import lru_cache
from pathlib import Path

import pytest

pytestmark = pytest.mark.contract

ROOT = Path(__file__).resolve().parents[2]
SKILL = ROOT / "skills" / "external" / "coaching-skills" / "SKILL.md"
OLD = "think-skills"
NEW = "coaching-skills"
UNIT = "skill:coaching-skills"
PROBE_ID = "skill-coaching-skills-wrapup"
SKILL_REL = "skills/external/coaching-skills/SKILL.md"
CALL_FORM = "coaching-skills <trainee-name|trainee-path> <work>"
TRIGGERS = ("教练", "陪练", "观察执行", "预期 vs 实际", "执行偏差", "微调建议", "coaching")

FROZEN_ROSTERS = (
    "tests/contract/test_expression_compatibility.py",
    "tests/contract/test_migration_distribution.py",
    "tests/contract/test_skill_layer_visibility_guards.py",
    "tests/contract/test_run_skills_wiring.py",
)

#: A10 residual members no generator reaches, pinned here (the guard copy is the one
#: sanctioned duplicate). Each entry states why it is not derivable.
PINNED_RESIDUAL_FILES = {
    # templates/commands is excluded from the templates mirror pair (per-tool fan-out owns it)
    "templates/commands/skills.md": "command source; per-tool copies are generated, the source is hand-edited",
    # not mirrored and not generated
    "src/specify_cli/__init__.py": "CLI upgrade registry; the sole permitted occurrence lives here",
    "docs/reference/agents/command-and-skills.md": "authored doc; no generator",
    "docs/tutorials/quickstart.md": "authored doc; no generator",
    # rendered probe face plus its map, regenerated by probe-utils.py (not by sync-mirrors)
    ".specify/memory/feedback/probe-map.md": "probe map; regenerated by probe-utils.py --action map",
    # rendered host agent copies; regenerated by specify render-agents
    ".qoder/agents": "rendered host agents; regenerated by specify render-agents",
}

SANCTIONED_START = "# OBSOLETE-ASSET-REGISTRY:START"
SANCTIONED_END = "# OBSOLETE-ASSET-REGISTRY:END"
SANCTIONED_RE = re.compile(
    re.escape(SANCTIONED_START) + r".*?" + re.escape(SANCTIONED_END), re.S
)

PER_FACE_ZERO = (
    ".qoder/agents",
    ".specify/agents/templates",
    ".specify/shared/definitions",
    ".specify/memory/feedback/probe-map.md",
)


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


@lru_cache(maxsize=None)
def _run(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=180,
    )


@lru_cache(maxsize=None)
def _sync_engine():
    path = ROOT / "scripts" / "python" / "sync-mirrors.py"
    spec = importlib.util.spec_from_file_location("_coaching_wiring_sync_engine", path)
    assert spec is not None and spec.loader is not None, f"cannot load {path}"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@lru_cache(maxsize=None)
def _cli():
    if str(ROOT / "src") not in sys.path:
        sys.path.insert(0, str(ROOT / "src"))
    import specify_cli  # noqa: PLC0415

    return specify_cli


def _tool_command_dirs() -> dict[str, Path]:
    """The regen engine's own fan-out table, filtered to the dirs present here."""
    out = {}
    for agent, rel in _cli()._ASSISTANT_COMMAND_DIRS.items():
        path = ROOT / rel
        if path.is_dir():
            out[agent] = path
    return out


def _files_under(base: Path) -> list[Path]:
    if base.is_file():
        return [base]
    if not base.is_dir():
        return []
    return sorted(p for p in base.rglob("*") if p.is_file())


def _candidate_faces() -> dict[str, list[Path]]:
    """Derive every face of the wiring surface (mirror pairs, copy targets, pinned)."""
    engine = _sync_engine()
    faces: dict[str, list[Path]] = {}
    for src_name, dst_name, _strict, exclude_parts in engine.MIRROR_PAIRS:
        for name in (src_name, dst_name):
            base = ROOT / name
            faces[name] = [base / rel for rel in engine.iter_files(base, exclude_parts)]
    for _agent, path in _tool_command_dirs().items():
        faces[str(path.relative_to(ROOT))] = sorted(path.glob("speckit.*"))
    for rel in PINNED_RESIDUAL_FILES:
        faces[rel] = _files_under(ROOT / rel)
    return faces


def _live_occurrences(path: Path) -> int:
    """Occurrences outside a sanctioned OBSOLETE-ASSET-REGISTRY block."""
    try:
        text = _read(path)
    except (UnicodeDecodeError, OSError):
        return 0
    return SANCTIONED_RE.sub("", text).count(OLD)


def _raw_occurrences(path: Path) -> int:
    try:
        return _read(path).count(OLD)
    except (UnicodeDecodeError, OSError):
        return 0


