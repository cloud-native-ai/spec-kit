def test_c4_cleanup_removes_the_entity_directory(tmp_path):
    project = tmp_path / "entity"
    skill_dir = project / ".specify" / "skills" / OLD
    skill_dir.mkdir(parents=True)
    (skill_dir / "SKILL.md").write_text("---\nname: x\n---\n", encoding="utf-8")

    removed = _cli().cleanup_obsolete_framework_assets(project, "qoder")

    assert not skill_dir.exists(), "the retired entity directory survived the upgrade sweep"
    assert f".specify/skills/{OLD}" in removed


def test_c4_cleanup_keeps_a_user_authored_symlink(tmp_path):
    project = tmp_path / "linked"
    (project / ".specify" / "skills").mkdir(parents=True)
    user_skill = project / "user-owned" / OLD
    user_skill.mkdir(parents=True)
    (user_skill / "SKILL.md").write_text("---\nname: mine\n---\n", encoding="utf-8")
    link = project / ".specify" / "skills" / OLD
    link.symlink_to(user_skill, target_is_directory=True)

    removed = _cli().cleanup_obsolete_framework_assets(project, "qoder")

    assert link.is_symlink() and link.exists(), "the user alias was removed with the directory"
    assert f".specify/skills/{OLD}" not in removed
    assert (user_skill / "SKILL.md").is_file(), "the symlink target was touched"


