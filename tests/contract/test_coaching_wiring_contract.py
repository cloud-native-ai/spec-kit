def _frontmatter(text: str) -> str:
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    assert match, "the skill has no frontmatter block"
    return match.group(1)


def _coordinate_source_directory() -> tuple[bool, str]:
    new_ok = SKILL.is_file()
    old_gone = not (ROOT / "skills" / "external" / OLD).exists()
    return new_ok and old_gone, f"new SKILL.md={new_ok} old dir absent={old_gone}"


def _coordinate_frontmatter_name() -> tuple[bool, str]:
    name = re.search(r"^name:\s*(\S+)\s*$", _frontmatter(_read(SKILL)), re.M)
    return bool(name and name.group(1) == NEW), f"name={name.group(1) if name else None}"


def _coordinate_resource_id() -> tuple[bool, str]:
    text = _read(SKILL)
    canonical = f"<SKILL:.specify/skills/{NEW}/SKILL.md>"
    declared = f'skill_id: "{canonical}"'
    ok = declared in text
    ok = ok and f"Canonical ID: `{canonical}`" in text
    ok = ok and f"Canonical Path: `.specify/skills/{NEW}/SKILL.md`" in text
    return ok, f"skill_id/Canonical ID/Path for {canonical}"


def _coordinate_runtime_unit() -> tuple[bool, str]:
    proc = _run("scripts/python/flow-class-check.py", "--action", "lookup", "--unit-id", UNIT)
    text = proc.stdout
    ok = (
        proc.returncode == 0
        and re.search(r"^source:\s*ledger\s*$", text, re.M) is not None
        and re.search(r"^flow_class:\s*execution\s*$", text, re.M) is not None
        and re.search(r"^basis:\s*behavior-oracle\s*$", text, re.M) is not None
    )
    return ok, text.strip().replace("\n", "; ")


def _coordinate_ledger_row() -> tuple[bool, str]:
    text = _read(ROOT / "shared" / "definitions" / "flow-class-definitions.md")
    rows = re.findall(
        rf"^\|\s*{re.escape(UNIT)}\s*\|\s*execution\s*\|\s*behavior-oracle\s*\|",
        text,
        re.M,
    )
    return len(rows) == 1, f"ledger rows={len(rows)}"


def _coordinate_probe_row() -> tuple[bool, str]:
    text = _read(ROOT / "shared" / "definitions" / "probe-definitions.md")
    row = re.search(
        rf"^\|\s*{re.escape(PROBE_ID)}\s*\|\s*skill-wrapup\s*\|\s*{re.escape(UNIT)}\s*\|",
        text,
        re.M,
    )
    check = _run("scripts/python/probe-utils.py", "--action", "compile-embeds", "--check")
    zero_drift = "zero drift" in check.stdout and check.returncode == 0
    return bool(row) and zero_drift, f"row={bool(row)} zero-drift={zero_drift}"


def _coordinate_route_row() -> tuple[bool, str]:
    text = _read(ROOT / "templates" / "commands" / "skills.md")
    table = text.split("### Routing", 1)[1].split("\n### ", 1)[0]
    rows = [
        line
        for line in table.splitlines()
        if line.startswith("|") and not set(line) <= set("|-: ")
    ]
    data_rows = [line.replace("\\|", "|") for line in rows if not line.startswith("| Condition")]
    target = [
        line
        for line in data_rows
        if f"`{SKILL_REL}`" in line and f"`{NEW}`" in line and CALL_FORM in line
    ]
    return len(data_rows) == 5 and len(target) == 1, (
        f"route rows={len(data_rows)} target rows={len(target)}"
    )


def _coordinate_description() -> tuple[bool, str]:
    description = _frontmatter(_read(SKILL))
    missing = [trigger for trigger in TRIGGERS if trigger not in description]
    has_call_form = CALL_FORM in description
    return not missing and has_call_form, f"missing={missing} call-form={has_call_form}"


def _coordinate_verdicts() -> dict[str, tuple[bool, str]]:
    return {
        "1-source-directory": _coordinate_source_directory(),
        "2-frontmatter-name": _coordinate_frontmatter_name(),
        "3-skill-id-resource-id": _coordinate_resource_id(),
        "4-runtime-unit-id": _coordinate_runtime_unit(),
        "5-flow-class-ledger-row": _coordinate_ledger_row(),
        "6-probe-row-and-compile": _coordinate_probe_row(),
        "7-route-row-and-path": _coordinate_route_row(),
        "8-description-triggers": _coordinate_description(),
    }


def test_c1_eight_identity_coordinates_all_hold():
    verdicts = _coordinate_verdicts()
    assert len(verdicts) == 8, f"coordinate count drifted: {len(verdicts)}"
    failing = {name: detail for name, (ok, detail) in verdicts.items() if not ok}
    assert not failing, "failing identity coordinates: " + repr(failing)
    passed = sum(1 for ok, _detail in verdicts.values() if ok)
    assert f"{passed}/{len(verdicts)}" == "8/8"


def test_c1_the_new_name_is_not_a_substring_of_itself_counted_twice():
    """`coaching-skills` inside `skill:coaching-skills` is one coordinate, not two."""
    assert NEW in UNIT
    assert len({UNIT.split(":", 1)[1], NEW}) == 1


