"""Contract test: compile → regen → sync propagation order (056 US3, T025).

The wrap-up face is derived in a fixed chain: registry/units change →
``probe-utils.py --action compile-embeds`` (framework-source faces) →
``regen-command-copies.py`` (per-tool copies) → ``sync-mirrors.py`` (.specify/
mirrors). A step skipped or run out of order leaves exactly one of the three
derived-state checks red while the others look green, so this suite runs the
three checks IN the canonical order and additionally pins the fingerprint
chain (banner fingerprint == fingerprint of the current runtime-face registry).
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import pytest

from tests.script_api import probe_utils

pytestmark = pytest.mark.contract

REPO_ROOT = Path(__file__).resolve().parents[2]
BANNER_FINGERPRINT = re.compile(r"fingerprint: ([0-9a-f]{12})")


def _fingerprint_of_runtime_registry() -> str:
    text = (REPO_ROOT / ".specify" / "shared" / "definitions"
            / "probe-definitions.md").read_text(encoding="utf-8")
    handlers = probe_utils._table_rows(text, "Handler")
    bindings = probe_utils._table_rows(text, "HandlerBinding")
    return probe_utils._fingerprint(handlers, bindings)


def test_compiled_fingerprints_match_the_runtime_registry():
    expected = _fingerprint_of_runtime_registry()
    checked = 0
    for base, pattern in (("templates/commands", "*.md"),
                          ("skills/internal", "*/SKILL.md"),
                          ("skills/external", "*/SKILL.md")):
        for path in sorted((REPO_ROOT / base).glob(pattern)):
            text = path.read_text(encoding="utf-8")
            if "AUTO-GENERATED by probe-utils.py" not in text:
                continue
            m = BANNER_FINGERPRINT.search(text)
            assert m, f"{path.relative_to(REPO_ROOT)}: compiled banner lost its fingerprint"
            assert m.group(1) == expected, (
                f"{path.relative_to(REPO_ROOT)}: banner fingerprint {m.group(1)} != "
                f"registry fingerprint {expected} — the registry moved without a "
                f"recompile (compile-embeds must precede regen/sync)"
            )
            checked += 1
    assert checked >= 60, f"only {checked} compiled faces found — walker broken"


def test_propagation_chain_is_green_in_canonical_order():
    # Step 1 — compile: the compiled faces match the registry (nothing to migrate).
    rc = probe_utils.main(["--action", "compile-embeds", "--check", "--format", "json"])
    assert rc == 0, (
        "step 1 (compile --check) red: the compiled faces drifted from the registry — "
        "run probe-utils.py --action compile-embeds BEFORE regen/sync"
    )
    # Step 2 — regen: per-tool copies match the (compiled) source templates.
    proc = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "python" / "regen-command-copies.py"),
         "--check"], capture_output=True, text=True, check=False)
    assert proc.returncode == 0, (
        "step 2 (regen --check) red: per-tool copies drifted from the compiled "
        "templates — run regen-command-copies.py after every compile-embeds"
    )
    # Step 3 — sync: the .specify mirrors match the sources.
    proc = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "python" / "sync-mirrors.py"),
         "--check"], capture_output=True, text=True, check=False)
    assert proc.returncode == 0, (
        "step 3 (sync --check) red: .specify mirrors drifted from the sources — run "
        "sync-mirrors.py after regen"
    )
