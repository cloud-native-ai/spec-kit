"""Contract test: compiled wrap-up wording is gate-safe (056 US3, T025).

Two guards: (1) every compiled `## Wrap-up` section is free of BLOCKING_PATTERNS
hits — the generator refuses such wording before write (exit 2), so a hit in the
tree means the wording gate was bypassed; (2) the confirmation-gate budget is
unchanged by the migration (total 23, violations 0 — PM-3).
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

import pytest

from tests.script_api import probe_utils

pytestmark = pytest.mark.contract

REPO_ROOT = Path(__file__).resolve().parents[2]
SCAN = REPO_ROOT / "scripts" / "python" / "scan-confirmation-gates.py"

BANNER = "AUTO-GENERATED by probe-utils.py --action compile-embeds"
FACE = re.compile(r"^## Wrap-up( |$)")


def compiled_sections() -> list[tuple[Path, str]]:
    out = []
    for base, pattern in (("templates/commands", "*.md"),
                          ("skills/internal", "*/SKILL.md"),
                          ("skills/external", "*/SKILL.md")):
        for path in sorted((REPO_ROOT / base).glob(pattern)):
            text = path.read_text(encoding="utf-8")
            lines = text.splitlines()
            body: list[str] = []
            in_face = False
            for line in lines:
                if line.startswith("## "):
                    in_face = bool(FACE.match(line))
                elif in_face:
                    body.append(line)
            section = "\n".join(body)
            if BANNER in section:
                out.append((path, section))
    return out


@pytest.mark.contract
def test_compiled_wording_hits_no_blocking_patterns():
    sections = compiled_sections()
    assert len(sections) >= 60, (
        f"only {len(sections)} compiled sections found — the section walker or the "
        f"compile migration is broken, making the wording assertion vacuous"
    )
    blocking = probe_utils._blocking_re()
    for path, section in sections:
        m = blocking.search(section)
        assert not m, (
            f"{path.relative_to(REPO_ROOT)}: compiled wrap-up wording hits "
            f"BLOCKING_PATTERNS ({m.group(0)!r}) — the generator must have refused "
            f"this; the wording gate was bypassed"
        )


@pytest.mark.contract
def test_confirmation_gate_budget_unchanged():
    proc = subprocess.run(
        [sys.executable, str(SCAN)], capture_output=True, text=True, check=False)
    out = proc.stdout
    m_total = re.search(r"blocking confirmation gates: (\d+)", out)
    m_viol = re.search(r"violations \(reversible gates still blocking\): (\d+)", out)
    assert m_total and m_viol, f"scan-confirmation-gates output unparsable:\n{out}{proc.stderr}"
    assert int(m_total.group(1)) == 23, (
        f"gate budget moved: {m_total.group(1)} != 23 — the compiled sections changed "
        f"the confirmation-gate surface; the budget owner must re-adjudicate first"
    )
    assert int(m_viol.group(1)) == 0, "reversible gates must not block"
