"""Contract for the ssh-utils transport skill and its wrapper.

Pins the invariant that motivated the skill: every non-interactive invocation
carries ``-o RemoteCommand=none``, a host-side preset is detected instead of
misread as a security block, and nested ``su -`` commands are POSIX-quoted
rather than hand-built. A fake ``ssh`` on PATH keeps the tests host-free.
"""
from __future__ import annotations

import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
SKILL = ROOT / "skills" / "external" / "ssh-utils" / "SKILL.md"
WRAPPER = ROOT / "skills" / "external" / "ssh-utils" / "scripts" / "ssh-exec.py"

pytestmark = pytest.mark.contract

FAKE_SSH = """#!/usr/bin/env bash
printf '%s\\n' "$@" >> "${FAKE_SSH_LOG:-/dev/null}"
if [ "${1:-}" = "-G" ]; then
  printf '%s\\n' "hostname 192.0.2.10" "user deploy" "port 22" \\
    "requesttty no" "remotecommand ${FAKE_SSH_PRESET:-none}" "proxyjump none"
  exit 0
fi
if [ -n "${FAKE_SSH_STDIN_OUT:-}" ]; then
  wc -c > "$FAKE_SSH_STDIN_OUT"
else
  cat > /dev/null
fi
[ -n "${FAKE_SSH_STDOUT:-}" ] && printf '%s' "$FAKE_SSH_STDOUT"
[ -n "${FAKE_SSH_STDERR:-}" ] && printf '%s' "$FAKE_SSH_STDERR" >&2
exit "${FAKE_SSH_EXIT:-0}"
"""


@pytest.fixture()
def fake_ssh(tmp_path: Path) -> Path:
    bindir = tmp_path / "bin"
    bindir.mkdir()
    shim = bindir / "ssh"
    shim.write_text(FAKE_SSH, encoding="utf-8")
    shim.chmod(0o755)
    return bindir


def _run(args: list[str], bindir: Path | None = None, env: dict | None = None):
    run_env = dict(os.environ)
    run_env.pop("PYTHONPATH", None)
    if bindir:
        run_env["PATH"] = f"{bindir}{os.pathsep}{run_env.get('PATH', '')}"
    if env:
        run_env.update(env)
    return subprocess.run(
        [sys.executable, str(WRAPPER), *args],
        capture_output=True, text=True, env=run_env,
    )


def _dry(args: list[str]) -> dict:
    proc = subprocess.run(
        [sys.executable, str(WRAPPER), *args, "--dry-run", "--json"],
        capture_output=True, text=True,
    )
    assert proc.returncode == 0, proc.stderr
    return json.loads(proc.stdout)


def test_skill_contract():
    text = SKILL.read_text(encoding="utf-8")
    assert "name: ssh-utils" in text
    assert 'skill_id: "<SKILL:.specify/skills/ssh-utils/SKILL.md>"' in text
    assert "classification: external" in text
    assert "## Wrap-up" in text
    assert "AUTO-GENERATED by probe-utils.py" in text
    assert WRAPPER.is_file()


@pytest.mark.parametrize("shape", [
    ["--cmd", "true"],
    ["--user", "deploy", "--cwd", "/srv/app", "--cmd", "true"],
    ["--script", __file__, "--script-arg=--x"],
    ["--upload", __file__, "--remote", "/tmp/x"],
    ["--download", "/tmp/x", "--local", __file__],
])
def test_every_execution_shape_carries_remote_command_none(shape):
    payload = _dry(["--host", "devbox", *shape])
    argv = payload["argv"]
    option_pairs = [argv[i:i + 2] for i in range(len(argv) - 1)]
    assert ["-o", "RemoteCommand=none"] in option_pairs


def test_nested_su_command_is_posix_quoted():
    payload = _dry(["--host", "devbox", "--user", "deploy",
                    "--cwd", "/srv/my app", "--cmd", "echo 'hi'"])
    parts = shlex.split(payload["remoteCommand"])
    assert parts[:4] == ["su", "-", "deploy", "-c"]
    assert parts[4] == "cd '/srv/my app' && echo 'hi'"


def test_tilde_stays_expandable():
    payload = _dry(["--host", "devbox", "--cwd", "~/work", "--cmd", "pwd"])
    assert payload["remoteCommand"] == 'cd "$HOME"/work && pwd'


def test_remotecommand_override_is_refused():
    proc = _run(["--host", "devbox", "--cmd", "true",
                 "--ssh-option", "RemoteCommand=tmux new", "--dry-run"])
    assert proc.returncode == 2
    assert "RemoteCommand=none" in proc.stderr


def test_exit_code_and_stdin_are_propagated(fake_ssh, tmp_path):
    stdin_out = tmp_path / "stdin.txt"
    exited = _run(["--host", "devbox", "--cmd", "false"], fake_ssh,
                  {"FAKE_SSH_EXIT": "7"})
    assert exited.returncode == 7
    script = tmp_path / "body.py"
    script.write_text("print('x')\n", encoding="utf-8")
    sent = _run(["--host", "devbox", "--script", str(script)], fake_ssh,
                {"FAKE_SSH_STDIN_OUT": str(stdin_out)})
    assert sent.returncode == 0
    assert int(stdin_out.read_text().strip()) == script.stat().st_size


def test_check_reports_preset_remote_command(fake_ssh):
    proc = _run(["--host", "devbox", "--check", "--json"], fake_ssh,
                {"FAKE_SSH_PRESET": "echo preset"})
    assert proc.returncode == 0
    payload = json.loads(proc.stdout)
    assert payload["remoteCommand"] == "echo preset"
    assert payload["remoteCommandPreset"] is True
    assert "RemoteCommand=none" in payload["mitigation"]
